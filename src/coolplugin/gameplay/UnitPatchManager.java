package coolplugin.gameplay;

import arc.Events;
import arc.files.Fi;
import arc.struct.Seq;
import arc.util.Log;
import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.util.Locale;
import mindustry.Vars;
import mindustry.ctype.ContentType;
import mindustry.game.EventType.DataPatchLoadEvent;
import mindustry.mod.DataPatcher;
import mindustry.mod.data.ContentAsset;
import mindustry.mod.data.DataAsset;
import mindustry.mod.data.PatchAsset;
import mindustry.type.UnitType;

/**
 * Server-load unit content health check and patch autogenerator (`config/assets/patches/`):
 * <ol>
 *   <li>{@code 00-autogen-itemcap.hjson}: multiplies every non-hidden unit's base {@code itemCapacity} by 5
 *       (or sets {@code 50} if {@code itemCapacity == 0}), running alphabetically before {@code bSpeedAndICap.hjson}.</li>
 *   <li>{@code zz-autogen-buildspeed.hjson}: checks all non-hidden units after configured patches are applied;
 *       for any unit without {@code buildSpeed > 0}, sets {@code buildSpeed} to {@code 0.5} when {@code health < 100},
 *       otherwise {@code sqrt(health / 100)}.</li>
 * </ol>
 */
public final class UnitPatchManager {

    public static final String AUTOGEN_ITEMCAP_FILE = "00-autogen-itemcap.hjson";
    public static final String AUTOGEN_BUILDSPEED_FILE = "zz-autogen-buildspeed.hjson";
    private static final String SERVER_ASSET_PREFIX = "server-assets/";

    private final Fi assetsDir;
    private final Fi patchesDir;
    private final Fi contentDir;
    private boolean fallbackHookRegistered = false;

    public UnitPatchManager(Fi dataDir) {
        this.assetsDir = dataDir.child("assets");
        this.patchesDir = assetsDir.child("patches");
        this.contentDir = assetsDir.child("content");
    }

    public void runOnServerLoad() {
        patchesDir.mkdirs();

        Seq<ContentAsset> contentAssets = readContentAssets();
        DataPatcher patcher = new DataPatcher();
        int itemCapCount = 0;
        int missingBuildSpeedCount = 0;

        try {
            // Pass 1: evaluate base + custom content units to compute 5x itemCapacity (0 -> 50) without compounding.
            patcher.apply(new Seq<>(), contentAssets, false);

            StringBuilder icapJson = new StringBuilder(2048);
            icapJson.append("{\n  \"name\": \"Autogenerated Unit Item Capacity (x5)\"");
            for (UnitType unit : Vars.content.units()) {
                if (isHiddenUnit(unit)) continue;
                int baseCap = unit.itemCapacity;
                int patchedCap = (baseCap <= 0) ? 50 : (baseCap * 5);
                icapJson.append(",\n  \"unit.").append(unit.name).append(".itemCapacity\": ").append(patchedCap);
                itemCapCount++;
            }
            icapJson.append("\n}\n");
            patchesDir.child(AUTOGEN_ITEMCAP_FILE).writeString(icapJson.toString(), false);

            // Pass 2: apply all patches except zz-autogen-buildspeed.hjson (including bSpeedAndICap.hjson) and run buildSpeed health check.
            Seq<PatchAsset> preCheckPatches = readPatchAssetsExcluding(AUTOGEN_BUILDSPEED_FILE);
            patcher.apply(preCheckPatches, contentAssets, false);

            StringBuilder bspeedJson = new StringBuilder(1024);
            bspeedJson.append("{\n  \"name\": \"Autogenerated Unit Build Speed Health Check\"");
            for (UnitType unit : Vars.content.units()) {
                if (isHiddenUnit(unit)) continue;
                if (unit.buildSpeed > 0f) continue;

                float maxHealth = unit.health;
                float computed = (maxHealth < 100f)
                    ? 0.5f
                    : round3((float) Math.sqrt(maxHealth / 100.0));
                bspeedJson.append(",\n  \"unit.").append(unit.name).append(".buildSpeed\": ")
                    .append(formatFloat(computed));
                missingBuildSpeedCount++;
            }
            bspeedJson.append("\n}\n");

            Fi bspeedFile = patchesDir.child(AUTOGEN_BUILDSPEED_FILE);
            if (missingBuildSpeedCount > 0) {
                bspeedFile.writeString(bspeedJson.toString(), false);
                Log.info("[CoolPlugin] Content health check: @ non-hidden unit(s) had no buildSpeed; autogenerated @.",
                    missingBuildSpeedCount, bspeedFile.path());
            } else {
                if (bspeedFile.exists()) {
                    bspeedFile.delete();
                }
                Log.info("[CoolPlugin] Content health check passed: all non-hidden units already have buildSpeed > 0.");
            }

            Log.info("[CoolPlugin] Autogenerated @ (@ non-hidden units).",
                patchesDir.child(AUTOGEN_ITEMCAP_FILE).path(), itemCapCount);
        } catch (Throwable t) {
            Log.err("[CoolPlugin] Failed during unit content health check / patch autogeneration", t);
        } finally {
            try {
                patcher.unapply(false);
            } catch (Throwable t) {
                Log.err("[CoolPlugin] Failed to unapply temporary DataPatcher", t);
            }
        }

        if (!reloadServerControlDataAssets()) {
            registerFallbackDataPatchHook();
        }
    }

    public static boolean isHiddenUnit(UnitType unit) {
        return unit == null || unit.isHidden() || unit.hidden || unit.internal;
    }

    private Seq<ContentAsset> readContentAssets() {
        Seq<ContentAsset> out = new Seq<>();
        if (!contentDir.exists()) return out;

        for (ContentType type : ContentType.all) {
            Fi folder = contentDir.child(type.name() + "s");
            if (!folder.exists()) continue;
            folder.walk(file -> {
                if (!isJsonOrHjson(file)) return;
                ContentAsset asset = new ContentAsset(file.nameWithoutExtension(), type, file.readString());
                asset.path = SERVER_ASSET_PREFIX + file.pathWithoutExtension().substring(contentDir.path().length() + 1);
                out.add(asset);
            });
        }
        out.sort();
        return out;
    }

    private Seq<PatchAsset> readPatchAssetsExcluding(String excludedFileName) {
        Seq<PatchAsset> out = new Seq<>();
        if (!patchesDir.exists()) return out;

        patchesDir.walk(file -> {
            if (!isJsonOrHjson(file)) return;
            if (excludedFileName != null && excludedFileName.equalsIgnoreCase(file.name())) return;
            PatchAsset asset = new PatchAsset(file.readString());
            asset.path = SERVER_ASSET_PREFIX + file.name();
            out.add(asset);
        });
        out.sort();
        return out;
    }

    private static boolean isJsonOrHjson(Fi file) {
        String ext = file.extension();
        return "json".equalsIgnoreCase(ext) || "hjson".equalsIgnoreCase(ext);
    }

    private static float round3(float value) {
        return Math.round(value * 1000f) / 1000f;
    }

    private static String formatFloat(float value) {
        String s = String.format(Locale.ROOT, "%.3f", value);
        while (s.contains(".") && (s.endsWith("0") || s.endsWith("."))) {
            boolean dot = s.endsWith(".");
            s = s.substring(0, s.length() - 1);
            if (dot) break;
        }
        return s;
    }

    private boolean reloadServerControlDataAssets() {
        try {
            Class<?> scClass = Class.forName("mindustry.server.ServerControl");
            Field instanceField = scClass.getField("instance");
            Object scInstance = instanceField.get(null);
            if (scInstance == null) return false;

            Method loadMethod = scClass.getDeclaredMethod("loadDataAssets");
            loadMethod.setAccessible(true);
            loadMethod.invoke(scInstance);
            return true;
        } catch (Throwable ignored) {
            return false;
        }
    }

    private void registerFallbackDataPatchHook() {
        if (fallbackHookRegistered) return;
        fallbackHookRegistered = true;

        Events.on(DataPatchLoadEvent.class, event -> {
            for (PatchAsset patch : readPatchAssetsExcluding(null)) {
                if (!event.assets.contains(existing -> existing instanceof PatchAsset && patch.path.equals(existing.path))) {
                    event.assets.add(patch);
                }
            }
            for (ContentAsset content : readContentAssets()) {
                if (!event.assets.contains(existing -> existing instanceof ContentAsset && content.path.equals(existing.path))) {
                    event.assets.add(content);
                }
            }
            event.assets.sort();
        });
    }
}
